_WS = re.compile(r"\s+")


def normalize(text: str) -> str:
    """Lowercase, strip accents, fold punctuation to single spaces."""
    text = text.lower().replace("œ", "oe").replace("æ", "ae")
    text = unicodedata.normalize("NFKD", text)
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return _WS.sub(" ", text).strip()


def _token_match(name_token: str, phrase_token: str) -> bool:
    """Exact token match plus regular plural endings (FR -s/-x,
    EN -s/-es, -y -> -ies, -o -> -oes). Keeps "vin" from matching
    "vinaigre" while letting "fraise" match "fraises"."""
    if name_token == phrase_token:
        return True
    if name_token in (phrase_token + "s", phrase_token + "x", phrase_token + "es"):
        return True
    return phrase_token.endswith("y") and name_token == phrase_token[:-1] + "ies"


def _phrase_matches_at(name_tokens: list[str], start: int, phrase_tokens: tuple[str, ...]) -> bool:
    return all(
        _token_match(name_tokens[start + j], phrase_tokens[j]) for j in range(len(phrase_tokens))
    )


def _compile() -> dict[str, list[tuple[int, str, str, str, tuple[str, ...]]]]:
    """Index phrases by first token so a name only tests phrases that
    can match it. Entries carry their rule order; the lowest wins,
    exactly like scanning RULES top to bottom."""
    index: dict[str, list[tuple[int, str, str, str, tuple[str, ...]]]] = {}
    for order, (rid, dept, sub, phrases) in enumerate(RULES):
        for phrase in phrases:
            tokens = tuple(normalize(phrase).split())
            if tokens:
                index.setdefault(tokens[0], []).append((order, rid, dept, sub, tokens))
    return index


_INDEX = _compile()


def classify_name(name: str) -> tuple[str, str, str] | None:
    """Classify one product name. Returns (department, subcategory,
    rule_id) or None. Matches are ranked first by position bucket
    (two tokens wide: the product a bundle names first wins over one
    named later), then by rule order (specific rules before generic),
    then by phrase length."""
    tokens = normalize(name).split()
    if not tokens:
        return None
    best: tuple[tuple[int, int, int], str, str, str] | None = None
    for i, token in enumerate(tokens):
        # The index is keyed by singular phrase tokens; a plural name
        # token must also try its singular forms.
        keys = {token}
        if token.endswith("ies") and len(token) > 3:
            keys.add(token[:-3] + "y")
        if token.endswith("es"):
            keys.add(token[:-2])
        if token.endswith(("s", "x")):
            keys.add(token[:-1])
        candidates = [e for k in keys for e in _INDEX.get(k, ())]
        for order, rid, dept, sub, phrase_tokens in candidates:
            rank = (i // 2, order, -len(phrase_tokens))
            if best is not None and rank >= best[0]:
                continue
            if len(tokens) - i < len(phrase_tokens):
                continue
            if _phrase_matches_at(tokens, i, phrase_tokens):
                best = (rank, dept, sub, rid)
    if best is None:
        return None
    return best[1], best[2], best[3]


